insert into "Recipes" as recipes ("Id", "Name", "Description", "Comment", "CookingTime") 
select 
	uuid_generate_v4(),
	(select rnt.name from recipe_names_temp as rnt offset series%1463 limit 1) || ' yo_' || series,
	'Description ' || (select rnt.name from recipe_names_temp as rnt offset series%1463 limit 1) || ' ' || series,
	'Comment ' || (select rnt.name from recipe_names_temp as rnt offset series%1463 limit 1) || ' ' || series,
	(case floor(random() * 10)::int
		when 1 then '00:10:00'
		when 2 then '00:20:00'
		when 3 then '00:30:00'
		when 4 then '00:45:00'
		when 5 then '00:55:00'
		when 6 then '00:05:00'
		when 7 then '01:15:00'
		when 8 then '01:25:00'
		when 9 then '01:35:00'
		when 0 then '01:45:00'
	end)::interval
from generate_series(1, 10000) as series